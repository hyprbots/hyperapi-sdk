"""Generate hyperapi/types/_generated.py from openapi/hyperapi-public.yaml.

    python scripts/generate_types.py           # write the models
    python scripts/generate_types.py --check   # CI: fail if the file is stale

The spec is the source of truth for response shapes; never edit
_generated.py by hand. Needs the `codegen` extra (pinned generator).
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "openapi" / "hyperapi-public.yaml"
# JSON keys that would hide HyperAPIModel's dict-style methods get a trailing
# underscore as the Python attribute (the JSON key itself is unchanged).
ALIASES = ROOT / "openapi" / "field-aliases.json"
OUT = ROOT / "hyperapi" / "types" / "_generated.py"
INIT = ROOT / "hyperapi" / "types" / "__init__.py"

HEADER = (
    "# GENERATED from openapi/hyperapi-public.yaml by scripts/generate_types.py.\n"
    "# Do not edit by hand: change the spec and regenerate."
)

ARGS = [
    "--input-file-type", "openapi",
    "--openapi-scopes", "schemas",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--base-class", "hyperapi.types._base.HyperAPIModel",
    # The generator's lowest target is 3.10; without the `X | Y` operator its
    # output (Optional[...], list[...]) also runs on 3.9, which CI tests.
    "--target-python-version", "3.10",
    "--no-use-union-operator",
    "--enum-field-as-literal", "all",
    "--use-standard-collections",
    "--use-schema-description",
    "--use-field-description",
    "--field-constraints",
    "--collapse-root-models",
    "--keep-model-order",
    "--disable-timestamp",
    "--strict-nullable",
    # Keep ids as the strings the API sends (0.7 returned str; a UUID object
    # would make `batch["batch_id"] == "..."` silently False).
    "--type-mappings", "uuid=string",
    "--aliases", str(ALIASES),
    "--custom-file-header", HEADER,
    # No generator-side formatting: ruff run from a temp dir would not see this
    # repo's config. generate() formats with the repo config explicitly instead.
    "--formatters", "builtin",
]


def generate() -> str:
    """The generated module's source.

    Always generated in an empty temp dir: the generator picks up formatting
    settings from any pyproject.toml above its output file, so generating in
    place and generating for --check would otherwise differ.
    """
    with tempfile.TemporaryDirectory() as d:
        out = Path(d) / "_generated.py"
        subprocess.run(
            [sys.executable, "-m", "datamodel_code_generator",
             "--input", str(SPEC), "--output", str(out), *ARGS],
            check=True,
        )
        subprocess.run(
            [sys.executable, "-m", "ruff", "format", "--quiet",
             "--config", str(ROOT / "pyproject.toml"), str(out)],
            check=True,
        )
        return out.read_text()


INIT_DOC = '''"""Typed response models for the HyperAPI SDK.

Every model is generated from ``openapi/hyperapi-public.yaml`` (see
``scripts/generate_types.py``), except :class:`ProcessResult`, which the SDK
composes. All models keep dict-style access (``result["result"]["ocr"]``) and
unknown fields; use ``.to_dict()`` for a plain ``dict``.
"""
'''


def init_source(generated: str) -> str:
    """hyperapi/types/__init__.py: re-export every generated model."""
    names = re.findall(r"^class (\w+)\(HyperAPIModel\)", generated, re.M)
    lines = [INIT_DOC, "# GENERATED by scripts/generate_types.py — do not edit by hand.", ""]
    lines += ["from ._base import HyperAPIModel", "from ._coerce import GenericResponse"]
    lines += ["from ._generated import ("] + [f"    {n}," for n in names] + [")"]
    lines += ["from ._sdk import ProcessResult", "", "__all__ = ["]
    lines += [f'    "{n}",' for n in ["HyperAPIModel", "GenericResponse", "ProcessResult", *names]]
    lines += ["]", ""]
    return "\n".join(lines)


def main() -> int:
    source = generate()
    want = {OUT: source, INIT: init_source(source)}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in want.items() if p.read_text() != text]
        if stale:
            print(f"stale: {', '.join(stale)} — run scripts/generate_types.py")
            return 1
        print("generated models match the spec")
        return 0
    for path, text in want.items():
        path.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} and {INIT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
